"""Edge device management (MVP 06): devices, groups, credentials, enrollment, heartbeats,
synchronization log, versioned configuration, aggregated event statistics."""

from __future__ import annotations

import enum
import uuid
from datetime import datetime

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base, BigIntPK, JSONType, TimestampMixin, UUIDPrimaryKeyMixin


class DeviceStatus(enum.StrEnum):
    ONLINE = "online"
    OFFLINE = "offline"
    DEGRADED = "degraded"
    SYNCHRONIZING = "synchronizing"
    ERROR = "error"
    REVOKED = "revoked"
    PENDING = "pending"  # registered, no heartbeat yet


class ConfigStatus(enum.StrEnum):
    PENDING = "pending"
    APPLIED = "applied"
    PARTIAL = "partial"
    FAILED = "failed"
    SUPERSEDED = "superseded"


def _in(values: type[enum.StrEnum]) -> str:
    return ", ".join(f"'{v.value}'" for v in values)


class DeviceGroup(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    __tablename__ = "device_groups"

    name: Mapped[str] = mapped_column(String(120), unique=True, nullable=False)
    description: Mapped[str | None] = mapped_column(Text)

    devices: Mapped[list[EdgeDevice]] = relationship(back_populates="group")


class EdgeDevice(TimestampMixin, Base):
    """One edge agent installation. ``id`` is the device UUID generated by the agent itself."""

    __tablename__ = "edge_devices"
    __table_args__ = (CheckConstraint(f"status IN ({_in(DeviceStatus)})", name="status_valid"),)

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True)
    name: Mapped[str] = mapped_column(String(120), nullable=False)
    description: Mapped[str | None] = mapped_column(Text)
    group_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("device_groups.id", ondelete="SET NULL"), index=True)
    status: Mapped[str] = mapped_column(String(20), nullable=False, default=DeviceStatus.PENDING.value, index=True)
    status_reason: Mapped[str | None] = mapped_column(String(300))
    status_changed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    agent_version: Mapped[str | None] = mapped_column(String(40))
    hardware: Mapped[dict] = mapped_column(JSONType, nullable=False, default=dict)
    # Latest heartbeat snapshot (health, AI, cameras, local sync queue)
    metrics: Mapped[dict] = mapped_column(JSONType, nullable=False, default=dict)
    ai_status: Mapped[dict] = mapped_column(JSONType, nullable=False, default=dict)
    camera_status: Mapped[dict] = mapped_column(JSONType, nullable=False, default=dict)
    sync_status: Mapped[dict] = mapped_column(JSONType, nullable=False, default=dict)
    heartbeat_interval_s: Mapped[int] = mapped_column(Integer, nullable=False, default=30)
    last_heartbeat_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), index=True)
    last_seen_ip: Mapped[str | None] = mapped_column(String(45))
    desired_config_version: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    applied_config_version: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    rotate_credentials: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    registered_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    group: Mapped[DeviceGroup | None] = relationship(back_populates="devices")


class DeviceCredential(UUIDPrimaryKeyMixin, Base):
    """Per-device secret. Only a SHA-256 hash is stored (secrets are 256-bit random values)."""

    __tablename__ = "device_credentials"

    device_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("edge_devices.id", ondelete="CASCADE"), nullable=False, index=True
    )
    secret_hash: Mapped[str] = mapped_column(String(64), nullable=False, unique=True)
    origin: Mapped[str] = mapped_column(String(20), nullable=False, default="enrollment")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    last_used_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    # Set on the old credential when a new one is issued: valid until then (grace period).
    expires_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class EnrollmentToken(UUIDPrimaryKeyMixin, Base):
    """One-time (or N-use) token an administrator hands to a new edge agent."""

    __tablename__ = "device_enrollment_tokens"

    name: Mapped[str | None] = mapped_column(String(120))
    token_hash: Mapped[str] = mapped_column(String(64), nullable=False, unique=True)
    group_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("device_groups.id", ondelete="SET NULL"))
    created_by: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    max_uses: Mapped[int] = mapped_column(Integer, nullable=False, default=1)
    uses: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class DeviceHeartbeat(Base):
    __tablename__ = "device_heartbeats"
    __table_args__ = (Index("ix_device_heartbeats_device_id_received_at", "device_id", "received_at"),)

    id: Mapped[int] = mapped_column(BigIntPK, primary_key=True, autoincrement=True)
    device_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("edge_devices.id", ondelete="CASCADE"), nullable=False)
    received_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    status: Mapped[str] = mapped_column(String(20), nullable=False)
    agent_version: Mapped[str | None] = mapped_column(String(40))
    cameras_online: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    cameras_total: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    ai_mode: Mapped[str | None] = mapped_column(String(20))
    queue_pending: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    metrics: Mapped[dict] = mapped_column(JSONType, nullable=False, default=dict)


class SynchronizationLog(Base):
    __tablename__ = "synchronization_logs"
    __table_args__ = (Index("ix_synchronization_logs_device_id_created_at", "device_id", "created_at"),)

    id: Mapped[int] = mapped_column(BigIntPK, primary_key=True, autoincrement=True)
    device_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("edge_devices.id", ondelete="CASCADE"))
    kind: Mapped[str] = mapped_column(String(30), nullable=False)  # events | configuration | registration | credentials
    status: Mapped[str] = mapped_column(String(20), nullable=False)  # ok | partial | failed
    received: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    accepted: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    duplicate: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    rejected: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    duration_ms: Mapped[int | None] = mapped_column(Integer)
    details: Mapped[dict] = mapped_column(JSONType, nullable=False, default=dict)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)


class DeviceConfiguration(UUIDPrimaryKeyMixin, Base):
    """Immutable configuration versions. A rollback creates a new version with older content."""

    __tablename__ = "device_configurations"
    __table_args__ = (
        UniqueConstraint("device_id", "version", name="uq_device_configurations_device_id_version"),
        CheckConstraint(f"status IN ({_in(ConfigStatus)})", name="status_valid"),
    )

    device_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("edge_devices.id", ondelete="CASCADE"), nullable=False, index=True
    )
    version: Mapped[int] = mapped_column(Integer, nullable=False)
    config: Mapped[dict] = mapped_column(JSONType, nullable=False, default=dict)
    checksum: Mapped[str] = mapped_column(String(64), nullable=False)
    comment: Mapped[str | None] = mapped_column(String(300))
    rollback_of: Mapped[int | None] = mapped_column(Integer)
    created_by: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    status: Mapped[str] = mapped_column(String(20), nullable=False, default=ConfigStatus.PENDING.value)
    acknowledged_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    ack: Mapped[dict] = mapped_column(JSONType, nullable=False, default=dict)


class EventStatistic(Base):
    """Hourly event counts per device / camera / type, maintained by the event processor."""

    __tablename__ = "event_statistics"
    __table_args__ = (
        UniqueConstraint("bucket_start", "device_id", "camera_ref", "event_type", name="uq_event_statistics_bucket"),
    )

    id: Mapped[int] = mapped_column(BigIntPK, primary_key=True, autoincrement=True)
    bucket_start: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, index=True)
    device_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("edge_devices.id", ondelete="CASCADE"), nullable=False)
    camera_ref: Mapped[str] = mapped_column(String(64), nullable=False)
    event_type: Mapped[str] = mapped_column(String(64), nullable=False)
    count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
